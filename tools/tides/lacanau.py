"""Generate Lacanau-Océan tide predictions for the trip and write src/tides.lacanau.ts.

July 2027 is beyond any live tide forecast and SHOM's official tables are licensed, so
the times are predicted astronomically from EOT20, an open global ocean-tide model
derived from satellite altimetry (DGFI-TUM, CC BY 4.0, doi:10.17882/79489), using pyTMD.

Before writing anything, the same prediction is scored against published high and low
waters for Lacanau (lacanau_reference.csv). The script refuses to write output if the
timing error exceeds MAX_RMS_MINUTES, so a bad model or setup cannot reach the app.

Setup (once):
    pip install pyTMD tzdata
    download https://www.seanoe.org/data/00683/79489/data/85762.zip (2.3 GB) and unzip
    its ocean_tides folder to <TIDE_MODELS>/EOT20/ocean_tides
Run:
    python tools/tides/lacanau.py [--models C:/Claude/Tools/tide-models]
"""
from __future__ import annotations

import argparse
import csv
from dataclasses import dataclass
from datetime import date, datetime, timedelta, timezone
from pathlib import Path
from zoneinfo import ZoneInfo

import numpy as np
import pyTMD.compute

HERE = Path(__file__).resolve().parent
OUT = HERE.parents[1] / 'src' / 'tides.lacanau.ts'
REFERENCE = HERE / 'lacanau_reference.csv'
DEFAULT_MODELS = Path('C:/Claude/Tools/tide-models')

MODEL = 'EOT20'
LAT, LON = 45.00, -1.23          # just off Lacanau-Océan beach, matching the "Lacanau (Large)" station
TRIP_START, TRIP_END = date(2027, 7, 11), date(2027, 7, 18)
LOCAL = ZoneInfo('Europe/Paris')
MAX_RMS_MINUTES = 12.0
EPOCH = datetime(1970, 1, 1, tzinfo=timezone.utc)


@dataclass(frozen=True)
class Turn:
    when: datetime   # UTC
    height: float    # metres relative to mean sea level
    high: bool


def predict(models: Path, start: datetime, end: datetime, step: timedelta = timedelta(minutes=1)):
    n = int((end - start) / step)
    seconds = (start - EPOCH).total_seconds() + np.arange(n) * step.total_seconds()
    h = pyTMD.compute.tide_elevations(
        np.array([LON]), np.array([LAT]), seconds, directory=models, model=MODEL,
        epoch=(1970, 1, 1, 0, 0, 0), type='time series', standard='UTC',
        extrapolate=True, cutoff=20.0)
    h = np.asarray(h, dtype=float).ravel()
    if np.isnan(h).any():
        raise SystemExit(f'{MODEL} has no ocean cell near {LAT}, {LON}')
    return start, step, h


def turning_points(models: Path, start: datetime, end: datetime) -> list[Turn]:
    """High and low waters from a 1-minute prediction, refined by parabolic interpolation."""
    t0, step, h = predict(models, start, end)
    turns: list[Turn] = []
    for i in range(1, len(h) - 1):
        is_max = h[i] > h[i - 1] and h[i] >= h[i + 1]
        is_min = h[i] < h[i - 1] and h[i] <= h[i + 1]
        if not (is_max or is_min):
            continue
        denom = h[i - 1] - 2 * h[i] + h[i + 1]
        offset = 0.5 * (h[i - 1] - h[i + 1]) / denom if denom else 0.0
        turns.append(Turn(t0 + (i + offset) * step, float(h[i]), bool(is_max)))
    return turns


def load_reference() -> list[Turn]:
    with REFERENCE.open(encoding='utf-8') as f:
        rows = csv.DictReader(line for line in f if not line.startswith('#'))
        return [Turn(datetime.fromisoformat(r['local_time']).astimezone(timezone.utc),
                     float(r['height_m']), r['kind'] == 'high') for r in rows]


def validate(models: Path) -> float:
    ref = load_reference()
    predicted = turning_points(models, ref[0].when - timedelta(hours=8), ref[-1].when + timedelta(hours=8))
    errors: dict[bool, list[float]] = {True: [], False: []}
    for r in ref:
        same = [p.when for p in predicted if p.high == r.high]
        errors[r.high].append(min(((p - r.when).total_seconds() / 60 for p in same), key=abs))
    for kind, errs in (('high', errors[True]), ('low', errors[False])):
        e = np.array(errs)
        print(f'{kind:>4} waters vs published: n={len(e)}, mean {e.mean():+.1f} min, '
              f'RMS {np.sqrt(np.mean(e ** 2)):.1f} min, worst {np.abs(e).max():.0f} min')
    return float(np.sqrt(np.mean(np.square(errors[True]))))


def render(turns: list[Turn], rms: float) -> str:
    rows = []
    day = TRIP_START
    while day <= TRIP_END:
        local = [t for t in turns if t.when.astimezone(LOCAL).date() == day]
        hm = lambda ts: ', '.join(f"'{t.when.astimezone(LOCAL):%H:%M}'" for t in ts)
        label = f'{day:%a} {day.day} {day:%b}'
        rows.append(f"  {{ date: '{day:%Y-%m-%d}', day: '{label}', high: [{hm([t for t in local if t.high])}], "
                    f"low: [{hm([t for t in local if not t.high])}] }},")
        day += timedelta(days=1)
    return (
        '// GENERATED by tools/tides/lacanau.py — do not edit by hand.\n'
        f'// Astronomical prediction for Lacanau-Océan ({LAT}, {LON}) from the {MODEL} ocean-tide model.\n'
        f'// High-water timing vs published Lacanau tables: RMS {rms:.0f} min.\n'
        "import type { TideDay } from './data';\n\n"
        'export const LACANAU_TIDES: TideDay[] = [\n' + '\n'.join(rows) + '\n];\n'
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('--models', type=Path, default=DEFAULT_MODELS, help='directory containing EOT20/')
    models = parser.parse_args().models
    rms = validate(models)
    if rms > MAX_RMS_MINUTES:
        raise SystemExit(f'high-water RMS {rms:.1f} min exceeds {MAX_RMS_MINUTES} min; not writing output')
    start = datetime.combine(TRIP_START - timedelta(days=1), datetime.min.time(), timezone.utc)
    end = datetime.combine(TRIP_END + timedelta(days=2), datetime.min.time(), timezone.utc)
    OUT.write_text(render(turning_points(models, start, end), rms), encoding='utf-8', newline='\n')
    print(f'wrote {OUT}')


if __name__ == '__main__':
    main()
